_IM_GLOBE = (32, 20.5, 11.5)


def _blob(pts, c=_IM_GLOBE):
    """Closed smooth outline (Catmull-Rom) through points given in globe units (-1..1)."""
    cx, cy, r = c
    P = [(cx + u * r, cy + v * r) for u, v in pts]
    n = len(P)
    out = [f"M{_f(P[0][0])} {_f(P[0][1])}"]
    for i in range(n):
        p0, p1, p2, p3 = P[i - 1], P[i], P[(i + 1) % n], P[(i + 2) % n]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        out.append(f"C{_f(c1[0])} {_f(c1[1])} {_f(c2[0])} {_f(c2[1])} {_f(p2[0])} {_f(p2[1])}")
    return "".join(out) + "z"


