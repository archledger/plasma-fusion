# ---- local helpers ---------------------------------------------------------------------------

def _f(v):
    return ("%.2f" % v).rstrip("0").rstrip(".")


_NUM = re.compile(r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")
_NARGS = dict(M=2, L=2, H=1, V=1, C=6, S=4, Q=4, T=2, A=7, Z=0)


def _parse(d):
    """SVG path data -> [(cmd, [numbers])], with packed arc flags ("a2 2 0 001 1") handled."""
    out, i, n, cmd = [], 0, len(d), None
    while True:
        while i < n and d[i] in " ,\t\r\n":
            i += 1
        if i >= n:
            break
        if d[i].isalpha():
            cmd = d[i]; i += 1
            if cmd in "Zz":
                out.append(("z", []))
                continue
        args = []
        for k in range(_NARGS[cmd.upper()]):
            while i < n and d[i] in " ,\t\r\n":
                i += 1
            if cmd.upper() == "A" and k in (3, 4):
                args.append(float(d[i])); i += 1
            else:
                m = _NUM.match(d, i)
                args.append(float(m.group())); i = m.end()
        out.append((cmd, args))
        if cmd == "M":
            cmd = "L"
        elif cmd == "m":
            cmd = "l"
    return out


def tp(d, s, tx, ty):
    """Any SVG path (relative or absolute) -> absolute path, scaled by s and moved by (tx, ty)."""
    X = lambda v: _f(v * s + tx)
    Y = lambda v: _f(v * s + ty)
    out = []
    cx = cy = sx = sy = 0.0
    for cmd, a in _parse(d):
        U, rel = cmd.upper(), cmd.islower()
        ox, oy = (cx, cy) if rel else (0.0, 0.0)
        if U == "Z":
            out.append("z"); cx, cy = sx, sy
        elif U == "M":
            cx, cy = a[0] + ox, a[1] + oy; sx, sy = cx, cy
            out.append(f"M{X(cx)} {Y(cy)}")
        elif U == "L" or U == "T":
            cx, cy = a[0] + ox, a[1] + oy
            out.append(f"L{X(cx)} {Y(cy)}")
        elif U == "H":
            cx = a[0] + (cx if rel else 0)
            out.append(f"L{X(cx)} {Y(cy)}")
        elif U == "V":
            cy = a[0] + (cy if rel else 0)
            out.append(f"L{X(cx)} {Y(cy)}")
        elif U == "C":
            p = [a[0] + ox, a[1] + oy, a[2] + ox, a[3] + oy, a[4] + ox, a[5] + oy]
            out.append(f"C{X(p[0])} {Y(p[1])} {X(p[2])} {Y(p[3])} {X(p[4])} {Y(p[5])}")
            cx, cy = p[4], p[5]
        elif U == "S" or U == "Q":
            p = [a[0] + ox, a[1] + oy, a[2] + ox, a[3] + oy]
            out.append(f"{U}{X(p[0])} {Y(p[1])} {X(p[2])} {Y(p[3])}")
            cx, cy = p[2], p[3]
        elif U == "A":
            ex, ey = a[5] + ox, a[6] + oy
            out.append(f"A{_f(a[0] * s)} {_f(a[1] * s)} {_f(a[2])} {int(a[3])} {int(a[4])} {X(ex)} {Y(ey)}")
            cx, cy = ex, ey
    return "".join(out)


