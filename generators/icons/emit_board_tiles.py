"""Emit the per-app tiles of the boards from the icon theme's drawings.

The boards draw their app icons through the AppIcon component (design/boards/AppIcon.dc.html);
since the 2026-10-02 per-app redesign (docs/parts/icons.md, "Per-app tiles") the drawings live in
generators/icons/apptiles. This tool writes the component's data table for the boarding keys whose
apps have a drawn tile of their own, and refreshes the two tablet boards, which are plain HTML with
the tile drawings embedded (they render without the component runtime), so a board render shows
what the theme ships.

    emit_board_tiles.py                # print the table, for review
    emit_board_tiles.py --write        # replace the block between the markers in
                                       # design/boards/AppIcon.dc.html and rewrite the embedded
                                       # tiles of design/boards/Tablet{,Light}.dc.html

The seam rule follows generators/icons/apptiles/kit.py: a layer drawn in the tile's own base colour
is painted once with that colour and once again with the sheen gradient (so the sheen band
continues over it without a seam). The component draws the second pass from each entry's `seams`
list; the tablet boards embed the same drawings as they come out of tile_svg().

The apps that use a board tile as it is (Konsole and the terminal tile, KCalc and the calculator
tile, NeoChat and the chat tile, Discover and the software tile, Weather, Plasma System Monitor,
Spectacle) need no component entry; the component's original board entries already draw them.
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import apptiles  # noqa: E402

# The keys the boards use that have a per-app tile (the launcher's default pins, the docks).
KEYS = [
    "dolphin", "firefox", "kmail", "kate", "elisa", "gwenview", "merkuro",
    "systemsettings", "marknote", "haruna", "marble",
]

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
COMPONENT = os.path.join(ROOT, "design", "boards", "AppIcon.dc.html")
TABLET = [os.path.join(ROOT, "design", "boards", "Tablet.dc.html"),
          os.path.join(ROOT, "design", "boards", "TabletLight.dc.html")]
BEGIN = "  // BEGIN per-app tiles (generated by generators/icons/emit_board_tiles.py)"
END = "  // END per-app tiles"

# The tablet boards' app tiles: label -> (source, key). "board:" keys come from the AppIcon
# component's original tiles (art_tiles), the others from apptiles.
TABLET_APPS = {
    "Dolphin": ("app", "dolphin"), "Firefox": ("app", "firefox"),
    "Konsole": ("board", "terminal"), "KMail": ("app", "kmail"), "Kate": ("app", "kate"),
    "Elisa": ("app", "elisa"), "Gwenview": ("app", "gwenview"), "KOrganizer": ("board", "calendar"),
    "System Settings": ("app", "systemsettings"), "KWrite": ("app", "kwrite"),
    "VLC": ("app", "vlc"), "NeoChat": ("board", "chat"), "Discover": ("board", "software"),
    "Okular": ("app", "okular"), "Weather": ("board", "weather"),
}


def js(s: str) -> str:
    return s.replace("\\", "\\\\").replace("'", "\\'")


def tile_of(source: str, key: str):
    import art_tiles  # noqa: E402  (the component's own board tiles)

    return art_tiles.TILES[key] if source == "board" else apptiles.TILES[key]


def seam_entries(tile) -> list[str]:
    """The sheen second pass of every layer drawn in the tile's base colour (kit.py's rule)."""
    base = tile["base"].lower()
    out = []
    for gname, cname in (("g1", "c1"), ("g2", "c2"), ("g3", "c3")):
        c = tile.get(cname, "")
        if tile.get(gname) and c and c.lower() == base:
            rule = "evenodd" if gname in ("g2", "g3") else "nonzero"
            out.append(f"{{ d: '{js(tile[gname])}', f: 1, rule: '{rule}' }}")
    c = tile.get("sc", "")
    if tile.get("s1") and c and c.lower() == base:
        out.append(f"{{ d: '{js(tile['s1'])}', st: 1, sw: {tile['sw']} }}")
    for d, c in tile.get("x", []):
        if c and c.lower() == base:
            out.append(f"{{ d: '{js(d)}', f: 1, rule: 'nonzero' }}")
    return out


def entry(key: str) -> str:
    tile = apptiles.TILES[key]
    fields = [f"label: '{js(tile['label'])}'", f"base: '{tile['base']}'", f"lip: '{tile['lip']}'"]
    for name, cname in (("g1", "c1"), ("g2", "c2"), ("g3", "c3")):
        if tile.get(name):
            fields.append(f"{name}: '{js(tile[name])}'")
            fields.append(f"{cname}: '{tile[cname]}'")
    if tile.get("s1"):
        fields += [f"s1: '{js(tile['s1'])}'", f"sc: '{tile['sc']}'", f"sw: {tile['sw']}"]
    if tile.get("x"):
        fields.append("xs: [" + ", ".join(f"['{js(d)}', '{c}']" for d, c in tile["x"]) + "]")
    seams = seam_entries(tile)
    if seams:
        fields.append("seams: [" + ", ".join(seams) + "]")
    return f"  {key}: {{ {', '.join(fields)} }},"


def block() -> str:
    lines = [BEGIN]
    for key in KEYS:
        lines.append(entry(key))
    lines.append(END)
    return "\n".join(lines)


def tile_svg_markup(tile, px: int) -> str:
    """One tile as the boards embed it: a single-line <svg> at the board's pixel size."""
    from apptiles import kit  # noqa: E402

    svg = kit.tile_svg(tile)
    inner = svg[svg.index(">") + 1:svg.rindex("</svg>")]
    inner = re.sub(r"\s*\n\s*", "", inner)
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{px}" height="{px}" viewBox="0 0 64 64">{inner}</svg>'


def tablet_html(path: str) -> str:
    """The tablet board's content with every embedded app tile refreshed from the drawings."""
    html = open(path).read()
    for label, (source, key) in TABLET_APPS.items():
        pattern = re.compile(
            r'(<button aria-label="' + re.escape(label) + r'"[^>]*>)(<svg .*?</svg>)(</button>)',
            re.S)

        def repl(m, source=source, key=key):
            width = int(re.search(r'width="(\d+)"', m.group(2)).group(1))
            return m.group(1) + tile_svg_markup(tile_of(source, key), width) + m.group(3)

        html, n = pattern.subn(repl, html)
        if n == 0:
            raise SystemExit(f"{path}: no {label} tile found")
    return html


def update_tablet() -> int:
    changed = 0
    for path in TABLET:
        new = tablet_html(path)
        if new != open(path).read():
            open(path, "w").write(new)
            changed += len(TABLET_APPS)
    return changed


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    text = block()
    if not args.write:
        print(text)
        return 0
    html = open(COMPONENT).read()
    if BEGIN not in html or END not in html:
        print(f"markers not found in {COMPONENT}", file=sys.stderr)
        return 1
    pre, rest = html.split(BEGIN, 1)
    _, post = rest.split(END, 1)
    open(COMPONENT, "w").write(pre + text + post)
    print(f"wrote {len(KEYS)} per-app tiles into {COMPONENT}")
    n = update_tablet()
    print(f"refreshed {n} embedded tiles in the tablet boards")
    return 0


if __name__ == "__main__":
    sys.exit(main())
