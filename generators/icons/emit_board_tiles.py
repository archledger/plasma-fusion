"""Emit the per-app tiles of design/boards/AppIcon.dc.html from the icon theme's drawings.

The boards draw their app icons through the AppIcon component (design/boards/AppIcon.dc.html);
since the 2026-10-02 per-app redesign (docs/parts/icons.md, "Per-app tiles") the drawings live in
generators/icons/apptiles. This tool writes the component's data table for the boarding keys whose
apps have a drawn tile of their own, so a board render shows what the theme ships.

    emit_board_tiles.py                # print the table, for review
    emit_board_tiles.py --write        # replace the block between the markers in
                                       # design/boards/AppIcon.dc.html

The apps that use a board tile as it is (Konsole and the terminal tile, KCalc and the calculator
tile, NeoChat and the chat tile, Discover and the software tile, Weather, Plasma System Monitor,
Spectacle) need no entry; the component's original board entries already draw them.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import apptiles  # noqa: E402

# The keys the boards use that have a per-app tile (the launcher's default pins, the docks).
KEYS = [
    "dolphin", "firefox", "kmail", "kate", "elisa", "gwenview", "merkuro",
    "systemsettings", "marknote", "haruna", "marble",
]

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
COMPONENT = os.path.join(ROOT, "design", "boards", "AppIcon.dc.html")
BEGIN = "  // BEGIN per-app tiles (generated by generators/icons/emit_board_tiles.py)"
END = "  // END per-app tiles"


def js(s: str) -> str:
    return s.replace("\\", "\\\\").replace("'", "\\'")


def entry(key: str) -> str:
    tile = apptiles.TILES[key]
    base = tile["base"]
    fields = [f"label: '{js(tile['label'])}'", f"base: '{base}'", f"lip: '{tile['lip']}'"]

    def color_of(c):
        return "url(#pf-sheen)" if c and c.lower() == base.lower() else c

    for name, cname in (("g1", "c1"), ("g2", "c2"), ("g3", "c3")):
        if tile.get(name):
            fields.append(f"{name}: '{js(tile[name])}'")
            fields.append(f"{cname}: '{color_of(tile[cname])}'")
    if tile.get("s1"):
        fields += [f"s1: '{js(tile['s1'])}'", f"sc: '{color_of(tile['sc'])}'", f"sw: {tile['sw']}"]
    if tile.get("x"):
        xs = []
        for d, c in tile["x"]:
            xs.append(f"['{js(d)}', '{color_of(c)}']")
        fields.append("xs: [" + ", ".join(xs) + "]")
    return f"  {key}: {{ {', '.join(fields)} }},"


def block() -> str:
    lines = [BEGIN]
    for key in KEYS:
        lines.append(entry(key))
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    text = block()
    if not args.write:
        print(text)
        return 0
    html = open(COMPONENT).read()
    if BEGIN not in html or END not in html:
        print(f"markers not found in {COMPONENT}", file=sys.stderr)
        return 1
    pre, rest = html.split(BEGIN, 1)
    _, post = rest.split(END, 1)
    open(COMPONENT, "w").write(pre + text + post)
    print(f"wrote {len(KEYS)} per-app tiles into {COMPONENT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
